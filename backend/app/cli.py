"""Developer commands.

python -m app.cli review-diff changes.diff --root .   # review a local diff
git diff main | python -m app.cli review-diff -       # ...or from stdin
python -m app.cli seed                                # fill the dashboard with demo data
"""

import argparse
import asyncio
import random
import sys
from datetime import timedelta
from pathlib import Path

from app.config import get_settings
from app.db import SessionLocal, init_db
from app.models import Review, ReviewComment, ReviewStatus, utcnow
from app.review.local import review_diff, to_markdown


async def cmd_review(args: argparse.Namespace) -> None:
    text = sys.stdin.read() if args.diff == "-" else Path(args.diff).read_text()
    result, ctx = await review_diff(text, get_settings(), root=args.root)
    print(to_markdown(result))
    print(f"\n<!-- {len(ctx.files)} files, {result.steps} agent steps, model {result.model} -->")


DEMO_REPOS = ["diravina/payments-api", "diravina/web-dashboard", "diravina/ml-pipeline"]
DEMO_ISSUES = [
    ("error", "security", "src/auth/login.py", "SQL query built with an f-string is injectable."),
    ("error", "bug", "src/orders/service.py", "`total` can be None here; this raises TypeError."),
    ("warning", "performance", "src/reports/export.py", "N+1 query inside the loop. Prefetch."),
    ("warning", "bug", "web/src/hooks/useCart.ts", "Effect is missing `userId` in its deps."),
    ("warning", "testing", "src/billing/refund.py", "Refund edge cases have no tests."),
    ("info", "maintainability", "src/utils/dates.py", "Duplicate of `parse_iso` in common/."),
    ("info", "style", "web/src/App.tsx", "Leftover console.log."),
    ("error", "security", "config/settings.py", "Possible secret committed (API key)."),
]
DEMO_TITLES = [
    "Add refund endpoint", "Fix cart total rounding", "Refactor auth middleware",
    "Export reports as CSV", "Upgrade React Router", "Add retry to payment webhook",
    "Cache product catalog", "Training job: early stopping",
]  # fmt: skip


async def cmd_seed(args: argparse.Namespace) -> None:
    await init_db()
    rng = random.Random(7)
    async with SessionLocal() as s:
        for i in range(args.count):
            created = utcnow() - timedelta(days=rng.randint(0, 13), hours=rng.randint(0, 23))
            issues = rng.sample(DEMO_ISSUES, rng.randint(0, 5))
            status = rng.choices(
                [ReviewStatus.COMPLETED, ReviewStatus.FAILED, ReviewStatus.SKIPPED], [90, 5, 5]
            )[0]
            if status != ReviewStatus.COMPLETED:
                issues = []
            verdict = (
                "request_changes"
                if any(x[0] == "error" for x in issues)
                else ("comment" if issues else "approve")
            )
            repo = rng.choice(DEMO_REPOS)
            review = Review(
                repo_full_name=repo,
                installation_id=0,
                pr_number=100 + i,
                pr_title=rng.choice(DEMO_TITLES),
                pr_author=rng.choice(["harshan", "priya-dev", "arun-k"]),
                pr_url=f"https://github.com/{repo}/pull/{100 + i}",
                head_sha=f"{rng.getrandbits(160):040x}",
                status=status,
                verdict=verdict if status == ReviewStatus.COMPLETED else None,
                summary="Demo review generated by `python -m app.cli seed`.",
                error="RateLimitError: retries exhausted"
                if status == ReviewStatus.FAILED
                else None,
                model="claude-sonnet-5-5",
                files_reviewed=rng.randint(1, 12),
                lint_issue_count=sum(1 for x in issues if x[1] == "security"),
                tests_status=rng.choice(["passed", "skipped"]),
                tokens_in=rng.randint(4000, 40000),
                tokens_out=rng.randint(500, 4000),
                attempts=1,
                duration_ms=rng.randint(8000, 60000),
                created_at=created,
                completed_at=created + timedelta(seconds=40),
            )
            review.comments = [
                ReviewComment(
                    path=path,
                    line=rng.randint(5, 200),
                    severity=sev,
                    category=cat,
                    source="lint" if "secret" in body else "llm",
                    body=body,
                    posted_inline=True,
                )  # fmt: skip
                for sev, cat, path, body in issues
            ]
            s.add(review)
        await s.commit()
    print(f"Seeded {args.count} demo reviews.")


def main() -> None:
    parser = argparse.ArgumentParser(prog="python -m app.cli")
    sub = parser.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("review-diff", help="review a unified diff file (or - for stdin)")
    r.add_argument("diff")
    r.add_argument("--root", help="repo root, so the agent can read full files")
    s = sub.add_parser("seed", help="insert demo reviews for the dashboard")
    s.add_argument("--count", type=int, default=40)
    args = parser.parse_args()
    asyncio.run({"review-diff": cmd_review, "seed": cmd_seed}[args.cmd](args))


if __name__ == "__main__":
    main()
